"""从 v0.1 的类型目录生成 Go 源码。

手抄 121 个类型（含模块、方言、参数上限、别名、额外参数）几乎必然会出错，
因此这里直接由 Python 版的权威目录生成 Go 字面量。

用法：
    python tools/gen_go_typecatalog.py

产物：
    internal/schema/typecatalog_gen.go
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "scripts"))

from gefjon.types import (  # noqa: E402
    MYSQL,
    POSTGRESQL,
    SQLALCHEMY,
    _SPECS,
)

TARGET = REPO_ROOT / "internal" / "schema" / "typecatalog_gen.go"

MODULE_CONST = {
    SQLALCHEMY: "ModuleSQLAlchemy",
    POSTGRESQL: "ModulePostgreSQL",
    MYSQL: "ModuleMySQL",
}


def go_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def go_string_slice(values) -> str:
    return "[]string{" + ", ".join(go_string(value) for value in values) + "}"


def render_spec(spec) -> str:
    fields = [f"Name: {go_string(spec.name)}", f"Module: {MODULE_CONST[spec.module]}"]
    if spec.dialect:
        fields.append(f"Dialect: {go_string(spec.dialect)}")
    if spec.min_args:
        fields.append(f"MinArgs: {spec.min_args}")
    if spec.max_args:
        fields.append(f"MaxArgs: {spec.max_args}")
    # Python 属性名 -> Go 字段名。UDT 是大写缩写，不能靠 title() 转换。
    bool_fields = {
        "takes_values": "TakesValues",
        "takes_item_type": "TakesItemType",
        "takes_timezone": "TakesTimezone",
        "takes_domain": "TakesDomain",
        "takes_not_null": "TakesNotNull",
        "udt": "UDT",
    }
    for attr, field_name in bool_fields.items():
        if getattr(spec, attr):
            fields.append(f"{field_name}: true")
    if spec.key:
        fields.append(f"Key: {go_string(spec.key)}")
    if spec.extra_args:
        fields.append(f"ExtraArgs: {go_string_slice(spec.extra_args)}")
    if spec.aliases:
        fields.append(f"Aliases: {go_string_slice(spec.aliases)}")
    return "\t{" + ", ".join(fields) + "},"


def main() -> int:
    lines = [
        "// Code generated by tools/gen_go_typecatalog.py from the v0.1 catalog. DO NOT EDIT.",
        "",
        "package schema",
        "",
        "// typeCatalog 是 v0.1 的类型目录，逐项由脚本生成，保证与 Python 版一致。",
        "var typeCatalog = []TypeSpec{",
    ]
    lines.extend(render_spec(spec) for spec in _SPECS)
    lines.append("}")
    lines.append("")

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines), encoding="utf-8")

    # 生成的文件也必须是 gofmt 合规的，否则每次生成后都要手工格式化
    try:
        subprocess.run(["gofmt", "-w", str(TARGET)], check=True)
    except (OSError, subprocess.CalledProcessError) as exc:
        print(f"[WARN] gofmt 不可用或执行失败，生成文件可能未格式化：{exc}")

    print(f"[OK] {len(_SPECS)} 个类型 -> {TARGET.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
